    expect(await textContrast(card.locator('.task-number'))).toBeGreaterThanOrEqual(4.5)
    await card.focus()
    await expect(card).toHaveCSS('outline-color', 'rgb(182, 184, 255)')
    await card.click()
    const details = page.getByRole('complementary', { name: 'Task 101 details' })
