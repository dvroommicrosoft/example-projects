async function textContrast(locator: Locator) {
  return locator.evaluate(element => {
    const rgb = (color: string) => color.match(/[\d.]+/g)!.map(Number)
    const luminance = (color: number[]) => color.slice(0, 3).map(value => {
      const channel = value / 255
      return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4
    }).reduce((sum, value, index) => sum + value * [0.2126, 0.7152, 0.0722][index], 0)
    let surface: Element | null = element
    while (surface && getComputedStyle(surface).backgroundColor === 'rgba(0, 0, 0, 0)') surface = surface.parentElement
    if (!surface) throw new Error('No opaque background found for contrast check')
    const foreground = luminance(rgb(getComputedStyle(element).color))
    const background = luminance(rgb(getComputedStyle(surface).backgroundColor))
    return (Math.max(foreground, background) + 0.05) / (Math.min(foreground, background) + 0.05)
  })
}

test('card navigation opens its Teams thread and details, supports reply, back, refresh, and close', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'Open task 101:' }).click()
  await expect(page).toHaveURL(/threads\/welcome-flow\?task=101$/)
  await expect(page.getByRole('heading', { name: 'Shape the onboarding experience', exact: true }).first()).toBeFocused()
  const details = page.getByRole('complementary', { name: 'Task 101 details' })
  await expect(details).toBeVisible()
  await expect(page.getByRole('region', { name: 'Selected Teams thread' }).getByText('I put together a first pass', { exact: false })).toBeVisible()
  await page.getByLabel('Reply to this thread').fill('Let’s review the mock together.')
  await page.getByRole('button', { name: 'Send reply', exact: true }).click()
  await expect(page.getByText('Let’s review the mock together.', { exact: true })).toBeVisible()
  await details.getByRole('button', { name: 'Expand task checklist' }).click()
  await details.getByLabel('Review the interactive prototype').check()
  await expect(details.getByLabel('Review the interactive prototype')).toBeChecked()
  await page.getByRole('button', { name: 'Back to board' }).click()
  await expect(page).toHaveURL(/board\?task=101$/)
  await expect(details).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(/threads\/welcome-flow\?task=101$/)
  await page.reload()
  await expect(details).toBeVisible()
  await page.getByRole('button', { name: 'Close task details' }).click()
  await expect(details).toHaveCount(0)
  await expect(page).toHaveURL(/threads\/welcome-flow$/)
})

test('board responds to its container width and hides only empty groups in narrow layout', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('./')
  const board = page.getByTestId('board-container')
  const blocked = page.getByRole('region', { name: 'Blocked tasks' })
  await expect(blocked).toBeVisible()
  expect(await board.evaluate(element => element.clientWidth)).toBeGreaterThanOrEqual(760)
  await page.getByRole('button', { name: 'Open task 101:' }).click()
  await page.getByRole('navigation', { name: 'Channel tabs' }).getByRole('button', { name: 'Workbench', exact: true }).click()
  expect(await board.evaluate(element => element.clientWidth)).toBeLessThan(760)
  await expect(blocked).toBeHidden()
  const groups = page.locator('.task-group:not(.empty-group)')
  const boxes = await groups.evaluateAll(elements => elements.map(element => ({ x: element.getBoundingClientRect().x, y: element.getBoundingClientRect().y })))
  expect(new Set(boxes.map(box => box.x)).size).toBe(1)
  expect(boxes[1].y).toBeGreaterThan(boxes[0].y)
  await page.getByRole('button', { name: 'Close task details' }).click()
  await expect(blocked).toBeVisible()
})

