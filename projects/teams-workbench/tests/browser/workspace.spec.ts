for (const width of [1600, 390]) {
  test(`OS theme is detected initially and switches live without losing task state at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: 'dark' })
    await page.goto('./')
    await expect(page.locator(':root')).toHaveCSS('color-scheme', 'light dark')
    await expect(page.locator('.teams-topbar')).toHaveCSS('background-color', 'rgb(41, 41, 41)')
    await expect(page.locator('.primary-pane')).toHaveCSS('background-color', 'rgb(31, 31, 31)')
    const card = page.getByRole('button', { name: 'Open task 101:' })
    await expect(card).toHaveCSS('background-color', 'rgb(46, 44, 41)')
    expect(await textContrast(card.locator('h4'))).toBeGreaterThanOrEqual(4.5)
    expect(await textContrast(card.locator('.task-number'))).toBeGreaterThanOrEqual(4.5)
    await card.focus()
    await expect(card).toHaveCSS('outline-color', 'rgb(182, 184, 255)')
    await card.click()
    const details = page.getByRole('complementary', { name: 'Task 101 details' })
    await expect(details).toHaveCSS('background-color', 'rgb(36, 35, 33)')
    expect(await textContrast(details.locator('.detail-header h2'))).toBeGreaterThanOrEqual(4.5)
    await page.getByLabel('Task status').selectOption('Blocked')
    const thread = page.getByRole('region', { name: 'Selected Teams thread' })
    await expect(thread).toHaveCSS('background-color', 'rgb(31, 31, 31)')
    await page.getByLabel('Reply to this thread').fill('@Workbench check the dark theme')
    await page.getByRole('button', { name: 'Send reply', exact: true }).click()
    const botReply = thread.locator('.thread-message').filter({ hasText: 'Bot · simulated' }).last()
    await expect(botReply).toContainText('status is Blocked')
    await expect(botReply.locator('.thread-bubble')).toHaveCSS('background-color', 'rgb(41, 41, 41)')
    expect(await textContrast(botReply.locator('.thread-bubble p'))).toBeGreaterThanOrEqual(4.5)
    expect(await textContrast(botReply.locator('.bot-badge'))).toBeGreaterThanOrEqual(4.5)
    await page.emulateMedia({ colorScheme: 'light' })
    await expect(page.locator('.teams-topbar')).toHaveCSS('background-color', 'rgb(232, 232, 232)')
    await expect(details).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(page.getByLabel('Task status')).toHaveValue('Blocked')
    await expect(botReply).toContainText('No action was performed.')
    await page.emulateMedia({ colorScheme: 'dark' })
    await expect(details).toHaveCSS('background-color', 'rgb(36, 35, 33)')
    await expect(page.getByLabel('Task status')).toHaveValue('Blocked')
    await expect(thread.locator('.thread-message')).toHaveCount(6)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  })
}
